def _replay(obs_a, obs_b, snapshots, beta, dynamics):
    """Doc §10 Steps 2-4 through the PRODUCTION state objects — the exact
    replay of tests/test_graph_temporal_state.py::_replay: source lease
    (carried flat, D4), advance-then-update ordering, hard certified residual
    updates (D3), published mark = beta * m_source + u."""
    res = empty_residual("cfg-v1")
    a_state = None
    a_marks, b_marks, updates, u_trace = [], [], [], []
    for t in snapshots:
        if t in obs_a:
            a_state = observation_state([obs_a[t], 0, 0], 1e-4, t, f"A@{t}")
        m_a, _ = a_state.carried_to(t)
        res = res.advance(t, dynamics)
        if t in obs_b:
            e = residual_measurement([obs_b[t], 0, 0], beta, m_a)
            r = residual_measurement_variance(1e-4, beta, a_state.variance, 1e4)
            res = res.updated_hard(e, r, t, f"B@{t}")
            updates.append(t)
        a_marks.append(m_a[0])
        b_marks.append(beta * m_a[0] + res.mean[0])
        u_trace.append(res.mean[0])
    return a_marks, b_marks, updates, u_trace


def _smooth_replay(obs_a, obs_b, snapshots):
    """The same observation sequence through the PRODUCTION smooth-field
    solver, run per snapshot with NO memory: only the nodes observed exactly
    at t are lit; when nothing is lit the previous PUBLISHED marks are carried
    in the plotting arrays only — the solver itself forgets everything."""
    graph = build_graph(["A", "B"], {("A", "B"): 1.0, ("B", "A"): 1.0})
    prior = build_increment_prior(graph, kappa=1e-3, eta=50.0)
    a_pub, b_pub = [], []
    for t in snapshots:
        idx, vals = [], []
        if t in obs_a:
            idx.append(0); vals.append(obs_a[t])
        if t in obs_b:
            idx.append(1); vals.append(obs_b[t])
        if not idx:  # dark snapshot: republish (display only — no state)
            assert a_pub, "first snapshot must be lit to seed the published arrays"
            a_pub.append(a_pub[-1]); b_pub.append(b_pub[-1])
            continue
        post = posterior_update(
            prior, np.zeros(2), np.full(2, 2.0),
            np.array(idx), np.array(vals), np.full(len(idx), 1e6),
        )
        a_pub.append(post.mean[0]); b_pub.append(post.mean[1])
    return a_pub, b_pub


