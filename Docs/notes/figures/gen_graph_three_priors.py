def _listing_operator(nodes, factors):
    """Note listing: assemble Q_msg from the factor rows (i, j, p, beta)."""
    n = len(nodes)
    Q = np.zeros((n, n))
    for i, j, p, b in factors:
        u = np.zeros(n)
        u[i] = 1.0
        u[j] = -b
        Q += p * np.outer(u, u)
    return Q


def _listing_solve(Q, kappa, obs, d, r):
    Qp = Q + np.diag(kappa)
    b = np.zeros(len(Q))
    Qp[obs, obs] += r
    b[obs] += r * d
    sigma = np.linalg.inv(Qp)
    return sigma @ b, sigma


def _listing_stationary(K):
    """Note listing (14_graph_extrapolation.tex lst:graph): pi^T K = pi^T."""
    n = len(K)
    S = K.T - np.eye(n)
    S[-1] = 1.0  # last row = mass constraint
    rhs = np.zeros(n)
    rhs[-1] = 1.0
    return np.linalg.solve(S, rhs)


def _listing_directed_laplacian_beta(K, pi, B):
    """Note listing: L_dir^beta = M^T Pi M, M = I - K∘B (PSD for any B)."""
    M = np.eye(len(K)) - K * B
    return M.T @ (pi[:, None] * M)


def verify_reference() -> None:
    # (i) MESSAGE: listing operator + dense solve vs production, and the
    # cycle gauge on a consistent / inconsistent triangle.
    nodes = ["A", "B", "C", "D"]
    edges = [message_edge("B", "A", 800.0, 1.3), message_edge("C", "B", 500.0, 0.8),
             message_edge("D", "C", 300.0, 1.1), message_edge("D", "A", 200.0, 0.9)]
    op = build_message_operator(nodes, edges)
    kappa = anchor_precisions(nodes, edges, {"custom": 0.5})
    obs, d, r = np.array([0]), np.array([1.0]), np.array([1e6])
    post = message_posterior_update(op, obs, d, r, anchor_precision=kappa)
    Q_ref = _listing_operator(nodes, op.factors)
    mean_ref, sigma_ref = _listing_solve(Q_ref, kappa, obs, d, r)
    dev_msg = max(
        float(np.max(np.abs(Q_ref - op.q_matrix))),
        float(np.max(np.abs(mean_ref - post.mean))),
        float(np.max(np.abs(np.diag(sigma_ref) - post.marginal_variance))),
    )
    good = [message_edge("B", "A", 1.0, 2.0), message_edge("C", "B", 1.0, 3.0),
            message_edge("C", "A", 1.0, 6.0)]
    bad = [message_edge("B", "A", 1.0, 2.0), message_edge("C", "B", 1.0, 3.0),
           message_edge("C", "A", 1.0, 5.0)]
    macro("gtpcycleflags", "%d", len(cycle_beta_products(["A", "B", "C"], good)))
    flags_bad = cycle_beta_products(["A", "B", "C"], bad)
    macro("gtpcyclebad", "%.3f", flags_bad[0].product if flags_bad else float("nan"))
    sci_macro("gtprefagreemsg", dev_msg)

    # (ii) LAYERED: hand-rolled chain S -> M -> T vs directed_pass, plus the
    # Dirichlet closed form -Q_FF^{-1} Q_FS d_S vs harmonic_posterior.
    p1, p2, b1, b2, v_s = 1e3, 2e3, 1.5, 0.8, 1e-4
    dg = build_directed_graph(
        ["S", "M", "T"],
        [directed_relation("M", "S", b1, p1), directed_relation("T", "M", b2, p2)],
    )
    dp = directed_pass(dg, {"S": ([1.0, 0.0, 0.0], [v_s] * 3)})
    m_m, v_m = b1 * 1.0, b1**2 * v_s + 1.0 / p1        # hand: one arc
    m_t, v_t = b2 * m_m, b2**2 * v_m + 1.0 / p2        # hand: composed
    dev_lay = max(
        abs(dp.predictions["M"].mean[0] - m_m),
        abs(dp.predictions["M"].variance[0] - v_m),
        abs(dp.predictions["T"].mean[0] - m_t),
        abs(dp.predictions["T"].variance[0] - v_t),
    )
    lad_t = {"1M": 1.0 / 12.0, "3M": 0.25, "6M": 0.5}
    lad_nodes = ["1M", "3M", "6M"]
    lad_edges = expand_calendar_ladder(lad_t)
    idx = {n: k for k, n in enumerate(lad_nodes)}
    Q = np.zeros((3, 3))
    for e in lad_edges:  # pairwise factors by hand (handle 0)
        i, j, p, b = idx[e.receiver], idx[e.informer], e.precision, e.beta[0]
        Q[i, i] += p
        Q[j, j] += p * b * b
        Q[i, j] -= p * b
        Q[j, i] -= p * b
    free, bound = [0, 2], [1]
    mean_free = -np.linalg.solve(Q[np.ix_(free, free)],
                                 Q[np.ix_(free, bound)] @ np.array([1.0]))
    hp = harmonic_posterior(lad_nodes, lad_edges, {"3M": 1.0})
    dev_lay = max(dev_lay, float(np.max(np.abs(mean_free - hp.mean[free]))))
    sci_macro("gtprefagreelay", dev_lay)

    # (iii) SMOOTH: the tex listing (stationary + L_dir^beta) vs production
    # build_graph / directed_residual_beta on a 4-node irreducible graph.
    w4 = {("A", "B"): 1.0, ("B", "C"): 0.8, ("C", "D"): 1.2, ("D", "A"): 0.6,
          ("B", "A"): 0.5, ("C", "B"): 0.5, ("D", "C"): 0.5, ("A", "D"): 0.5}
    g4 = build_graph(["A", "B", "C", "D"], w4)
    B = beta_matrix(g4, {("A", "B"): 1.2, ("C", "D"): 0.8})
    dev_sm = max(
        float(np.max(np.abs(_listing_stationary(g4.kernel) - g4.stationary))),
        float(np.max(np.abs(
            _listing_directed_laplacian_beta(g4.kernel, g4.stationary, B)
            - directed_residual_beta(g4, B)
        ))),
    )
    sci_macro("gtprefagreesm", dev_sm)


