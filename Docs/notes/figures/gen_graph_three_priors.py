def _solve_chain(eta: float):
    """8-node calendar chain, symmetric unit trust, one lit node (+1)."""
    tenors = ["1W", "1M", "2M", "3M", "6M", "9M", "1Y", "2Y"]
    weights: dict[tuple[str, str], float] = {}
    for near, far in zip(tenors, tenors[1:]):
        weights[(near, far)] = 1.0   # far informs near
        weights[(far, near)] = 1.0   # near informs far
    graph = build_graph(tenors, weights)
    prior = build_increment_prior(graph, kappa=0.2, eta=eta)
    post = posterior_update(
        prior, np.zeros(8), np.full(8, 2.0),
        np.array([3]), np.array([1.0]), np.array([100.0]),
    )
    return tenors, post


